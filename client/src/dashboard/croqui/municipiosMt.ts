export function findMunicipioMt(nomeOuIbge: string | null | undefined): MunicipioOption | null {
  if (!nomeOuIbge) return null;
  const search = nomeOuIbge.trim().toLowerCase();
  return (
    MUNICIPIOS_MT.find(
      (m) =>
        m.ibge === nomeOuIbge ||
        m.nome.toLowerCase() === search ||
        m.nome.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase() ===
          search.normalize("NFD").replace(/[\u0300-\u036f]/g, ""),
    ) || null
  );
}
